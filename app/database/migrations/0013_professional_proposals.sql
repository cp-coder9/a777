CREATE TABLE IF NOT EXISTS proposal_term_templates (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  template_key VARCHAR(80) NOT NULL,
  name VARCHAR(180) NOT NULL,
  profession VARCHAR(60) NOT NULL,
  version VARCHAR(40) NOT NULL,
  clauses JSON NOT NULL,
  editable TINYINT(1) NOT NULL DEFAULT 1,
  legal_review_required TINYINT(1) NOT NULL DEFAULT 1,
  status ENUM('draft','verified','retired') NOT NULL DEFAULT 'draft',
  created_by BINARY(16) NOT NULL,
  reviewed_by BINARY(16) NULL,
  reviewed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_proposal_term_version (organisation_id,template_key,version),
  KEY idx_proposal_terms_library (organisation_id,profession,status),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (reviewed_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS professional_proposals (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  fee_run_id BINARY(16) NOT NULL,
  created_by BINARY(16) NOT NULL,
  title VARCHAR(255) NOT NULL,
  client_name VARCHAR(180) NOT NULL,
  client_email VARCHAR(320) NOT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  status ENUM('draft','issued','accepted','declined','expired','superseded') NOT NULL DEFAULT 'draft',
  validity_days SMALLINT UNSIGNED NOT NULL,
  legal_review_required TINYINT(1) NOT NULL DEFAULT 1,
  legal_review_confirmed_at DATETIME(6) NULL,
  professional_confirmed_at DATETIME(6) NULL,
  issue_reason VARCHAR(500) NULL,
  document_snapshot JSON NOT NULL,
  audit_hash CHAR(64) NULL,
  issued_at DATETIME(6) NULL,
  expires_at DATETIME(6) NULL,
  accepted_at DATETIME(6) NULL,
  supersedes_proposal_id BINARY(16) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  KEY idx_proposals_project (organisation_id,project_id,created_at),
  KEY idx_proposals_status (organisation_id,status,expires_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (fee_run_id) REFERENCES tool_runs(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (supersedes_proposal_id) REFERENCES professional_proposals(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS proposal_acceptance_requests (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  proposal_id BINARY(16) NOT NULL,
  recipient_email VARCHAR(320) NOT NULL,
  token_hash CHAR(64) NOT NULL,
  status ENUM('pending','accepted','declined','revoked','expired') NOT NULL DEFAULT 'pending',
  accepted_by VARCHAR(180) NULL,
  responsibility_confirmed TINYINT(1) NOT NULL DEFAULT 0,
  accepted_ip VARCHAR(64) NULL,
  accepted_user_agent VARCHAR(500) NULL,
  expires_at DATETIME(6) NOT NULL,
  accepted_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_proposal_acceptance_token (token_hash),
  KEY idx_proposal_acceptance (proposal_id,status),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (proposal_id) REFERENCES professional_proposals(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
