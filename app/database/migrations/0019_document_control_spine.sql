CREATE TABLE IF NOT EXISTS controlled_documents (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  title VARCHAR(220) NOT NULL,
  document_type ENUM('drawing','specification','appointment','approval_letter','municipal_form','submission_pack','tender_pack','rfi','site_instruction','payment_certificate','closeout_certificate','warranty','closeout_pack') NOT NULL,
  discipline ENUM('architectural','structural','civil','electrical','mechanical','fire','quantity_surveying','general') NOT NULL,
  phase ENUM('onboarding','feasibility','appointment','concept_design','design_development','municipal_submission','tender_procurement','construction_execution','closeout') NOT NULL,
  author_role VARCHAR(60) NOT NULL,
  reviewer_role VARCHAR(60) NOT NULL,
  current_revision_id BINARY(16) NULL,
  created_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  KEY idx_controlled_documents_project (organisation_id,project_id,document_type,phase),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

