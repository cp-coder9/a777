CREATE TABLE IF NOT EXISTS specforge_workspaces (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  title VARCHAR(220) NOT NULL,
  revision_code VARCHAR(40) NOT NULL,
  issue_purpose ENUM('for_review','for_information','for_tender','for_construction') NOT NULL,
  status ENUM('draft','issued') NOT NULL DEFAULT 'draft',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  snapshot_payload JSON NULL,
  snapshot_sha256 CHAR(64) NULL,
  document_id BINARY(16) NULL,
  document_revision_id BINARY(16) NULL,
  project_record_id BINARY(16) NULL,
  issue_reason VARCHAR(500) NULL,
  professional_role VARCHAR(80) NULL,
  created_by BINARY(16) NOT NULL,
  issued_by BINARY(16) NULL,
  issued_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_specforge_workspace_revision (organisation_id,project_id,title,revision_code),
  KEY idx_specforge_workspace_project (organisation_id,project_id,status,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (document_id) REFERENCES controlled_documents(id),
  FOREIGN KEY (document_revision_id) REFERENCES document_revisions(id),
  FOREIGN KEY (project_record_id) REFERENCES project_records(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (issued_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS specforge_sections (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  workspace_id BINARY(16) NOT NULL,
  code VARCHAR(40) NOT NULL,
  title VARCHAR(220) NOT NULL,
  discipline VARCHAR(80) NOT NULL,
  owner_role VARCHAR(80) NOT NULL,
  reviewer_role VARCHAR(80) NOT NULL,
  approver_role VARCHAR(80) NOT NULL,
  created_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_specforge_section_code (workspace_id,code),
  KEY idx_specforge_sections_project (organisation_id,project_id,workspace_id),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (workspace_id) REFERENCES specforge_workspaces(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS specforge_items (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  workspace_id BINARY(16) NOT NULL,
  section_id BINARY(16) NOT NULL,
  code VARCHAR(80) NOT NULL,
  title VARCHAR(220) NOT NULL,
  room_name VARCHAR(180) NOT NULL DEFAULT '',
  package_name VARCHAR(180) NOT NULL DEFAULT '',
  supplier VARCHAR(220) NOT NULL DEFAULT '',
  model_name VARCHAR(220) NOT NULL DEFAULT '',
  finish_name VARCHAR(220) NOT NULL DEFAULT '',
  dimensions VARCHAR(220) NOT NULL DEFAULT '',
  drawing_references JSON NOT NULL,
  clause_references JSON NOT NULL,
  budget_allowance_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
  estimated_cost_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
  lead_time_days SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  requires_client_decision TINYINT(1) NOT NULL DEFAULT 0,
  owner_role VARCHAR(80) NOT NULL,
  reviewer_role VARCHAR(80) NOT NULL,
  approver_role VARCHAR(80) NOT NULL,
  sustainability VARCHAR(1000) NOT NULL DEFAULT '',
  warranty VARCHAR(1000) NOT NULL DEFAULT '',
  notes TEXT NOT NULL,
  status ENUM('draft','approved','rejected','flagged') NOT NULL DEFAULT 'draft',
  created_by BINARY(16) NOT NULL,
  decided_by BINARY(16) NULL,
  decided_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_specforge_item_code (workspace_id,code),
  KEY idx_specforge_items_status (organisation_id,project_id,workspace_id,status),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (workspace_id) REFERENCES specforge_workspaces(id),
  FOREIGN KEY (section_id) REFERENCES specforge_sections(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (decided_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

