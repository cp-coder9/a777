  action ENUM('approve','reject','flag') NOT NULL,
  acting_role VARCHAR(80) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  decided_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  KEY idx_specforge_decisions_item (organisation_id,project_id,item_id,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (workspace_id) REFERENCES specforge_workspaces(id),
  FOREIGN KEY (item_id) REFERENCES specforge_items(id),
  FOREIGN KEY (decided_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
