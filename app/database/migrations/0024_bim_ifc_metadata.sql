CREATE TABLE IF NOT EXISTS model_sources (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  title VARCHAR(220) NOT NULL,
  source_format ENUM('ifc','ifc_json','revit_schedule_csv','cobie_csv','bcf','manual') NOT NULL,
  schema_version VARCHAR(80) NOT NULL,
  source_revision VARCHAR(80) NOT NULL,
  file_id BINARY(16) NULL,
  original_filename VARCHAR(255) NOT NULL DEFAULT '',
  source_sha256 CHAR(64) NULL,
  extraction_mode ENUM('human_entered','structured_export') NOT NULL,
  provider_name VARCHAR(180) NOT NULL DEFAULT '',
  assumptions JSON NOT NULL,
  responsible_role VARCHAR(80) NOT NULL,
  status ENUM('draft','issued') NOT NULL DEFAULT 'draft',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  issued_revision_id BINARY(16) NULL,
  snapshot_sha256 CHAR(64) NULL,
  project_record_id BINARY(16) NULL,
  issue_reason VARCHAR(500) NULL,
  issued_by BINARY(16) NULL,
  issued_at DATETIME(6) NULL,
  created_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_model_source_revision (organisation_id,project_id,title,source_revision),
  KEY idx_model_source_project (organisation_id,project_id,status,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (file_id) REFERENCES stored_files(id),
  FOREIGN KEY (project_record_id) REFERENCES project_records(id),
  FOREIGN KEY (issued_by) REFERENCES users(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

