CREATE TABLE IF NOT EXISTS planning_applications (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NULL,
  application_number VARCHAR(80) NOT NULL,
  application_type ENUM('rezoning','consent_use','subdivision','consolidation','removal_restrictions','township_establishment','site_development_plan','other') NOT NULL,
  title VARCHAR(220) NOT NULL,
  municipality VARCHAR(220) NOT NULL,
  property_reference VARCHAR(220) NOT NULL,
  responsible_role VARCHAR(80) NOT NULL,
  source_basis JSON NOT NULL,
  stage ENUM('pre_application','preparation','submission','validation','participation','assessment','decision','appeal','conditions') NOT NULL DEFAULT 'preparation',
  status ENUM('draft','active','approved','refused','withdrawn','completed') NOT NULL DEFAULT 'draft',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  external_reference VARCHAR(180) NULL,
  external_submission_claimed TINYINT(1) NOT NULL DEFAULT 0,
  submission_reason VARCHAR(500) NULL,
  snapshot_payload JSON NULL,
  snapshot_sha256 CHAR(64) NULL,
  project_record_id BINARY(16) NULL,
  submitted_by BINARY(16) NULL,
  submitted_at DATETIME(6) NULL,
  created_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_planning_application_number (organisation_id,application_number),
  KEY idx_planning_project (organisation_id,project_id,status,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (project_record_id) REFERENCES project_records(id),
  FOREIGN KEY (submitted_by) REFERENCES users(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS planning_register_entries (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  application_id BINARY(16) NOT NULL,
  entry_type ENUM('document','deadline','participation','condition','hearing','appeal','municipality_profile','fee','message') NOT NULL,
  title VARCHAR(220) NOT NULL,
  status VARCHAR(60) NOT NULL,
  required_flag TINYINT(1) NOT NULL DEFAULT 0,
  basis VARCHAR(500) NOT NULL DEFAULT '',
  due_at DATETIME(6) NULL,
  amount_cents BIGINT UNSIGNED NULL,
  payload JSON NOT NULL,
  created_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  KEY idx_planning_entry_register (organisation_id,application_id,entry_type,due_at,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (application_id) REFERENCES planning_applications(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS planning_application_events (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  application_id BINARY(16) NOT NULL,
  event_type VARCHAR(80) NOT NULL,
  from_stage VARCHAR(40) NULL,
  to_stage VARCHAR(40) NULL,
  reason VARCHAR(500) NOT NULL,
  external_reference VARCHAR(180) NULL,
  payload JSON NOT NULL,
  actor_user_id BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  KEY idx_planning_events (organisation_id,application_id,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (application_id) REFERENCES planning_applications(id),
  FOREIGN KEY (actor_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
