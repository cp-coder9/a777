CREATE TABLE IF NOT EXISTS regulatory_cases (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  case_number VARCHAR(80) NOT NULL,
  case_type ENUM('environmental','heritage') NOT NULL,
  title VARCHAR(220) NOT NULL,
  authority_name VARCHAR(220) NOT NULL,
  responsible_role VARCHAR(80) NOT NULL,
  source_basis JSON NOT NULL,
  status ENUM('draft','determined','active','closed') NOT NULL DEFAULT 'draft',
  version INT UNSIGNED NOT NULL DEFAULT 1,
  determination_route VARCHAR(80) NULL,
  external_reference VARCHAR(180) NULL,
  determination_reason VARCHAR(500) NULL,
  snapshot_payload JSON NULL,
  snapshot_sha256 CHAR(64) NULL,
  project_record_id BINARY(16) NULL,
  determined_by BINARY(16) NULL,
  determined_at DATETIME(6) NULL,
  created_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_regulatory_case_number (organisation_id,case_number),
  KEY idx_regulatory_project (organisation_id,project_id,case_type,status,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (project_record_id) REFERENCES project_records(id),
  FOREIGN KEY (determined_by) REFERENCES users(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS regulatory_case_evidence (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  case_id BINARY(16) NOT NULL,
  evidence_type ENUM('screening_report','site_sensitivity_verification','listed_activity_review','specialist_study','public_participation','empr','monitoring','audit','heritage_nid','heritage_impact_assessment','authority_correspondence','permit','condition') NOT NULL,
  title VARCHAR(220) NOT NULL,
  status ENUM('draft','pending','complete','submitted_externally','received','accepted','rejected','closed') NOT NULL,
  external_reference VARCHAR(180) NOT NULL,
  source_url VARCHAR(1000) NOT NULL,
  observed_on DATE NOT NULL,
  payload JSON NOT NULL,
  created_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  KEY idx_regulatory_evidence (organisation_id,case_id,evidence_type,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (case_id) REFERENCES regulatory_cases(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
