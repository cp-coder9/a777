CREATE TABLE IF NOT EXISTS dedicated_app_installations (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NULL,
  app_id VARCHAR(80) NOT NULL,
  name VARCHAR(180) NOT NULL,
  version VARCHAR(80) NOT NULL,
  build_commit CHAR(40) NOT NULL,
  device_id VARCHAR(180) NOT NULL,
  credential_hash CHAR(64) NOT NULL,
  status ENUM('integration_required','registered','online','degraded','revoked','disabled') NOT NULL DEFAULT 'registered',
  capabilities JSON NOT NULL,
  runtime_provenance JSON NOT NULL,
  audit_writer_ready BOOLEAN NOT NULL DEFAULT FALSE,
  file_manager_writer_ready BOOLEAN NOT NULL DEFAULT FALSE,
  last_sync_status ENUM('never','synced','conflict','failed') NOT NULL DEFAULT 'never',
  last_seen_at DATETIME(6) NULL,
  created_by BINARY(16) NOT NULL,
  revoked_by BINARY(16) NULL,
  revoked_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_dedicated_app_device (organisation_id,app_id,device_id),
  UNIQUE KEY uq_dedicated_app_credential (credential_hash),
  KEY idx_dedicated_app_status (organisation_id,status,app_id),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (revoked_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dedicated_app_workflow_events (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NULL,
  installation_id BINARY(16) NOT NULL,
  actor_user_id BINARY(16) NOT NULL,
  external_event_id VARCHAR(180) NOT NULL,
  event_type VARCHAR(100) NOT NULL,
  summary VARCHAR(1000) NOT NULL,
  outputs JSON NOT NULL,
  human_gate ENUM('none','review','approval','signature','payment_release','municipal_submission','professional_certification','closeout_acceptance') NOT NULL,
  risk_level ENUM('low','medium','high','critical') NOT NULL,
  file_refs JSON NOT NULL,
  status ENUM('allowed','requires_human','blocked','completed') NOT NULL,
  blockers JSON NOT NULL,
  warnings JSON NOT NULL,
  ai_may_execute BOOLEAN NOT NULL DEFAULT FALSE,
  payload_sha256 CHAR(64) NOT NULL,
  confirmed_by BINARY(16) NULL,
  confirmation_reason VARCHAR(1000) NULL,
  confirmed_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_dedicated_app_external_event (installation_id,external_event_id),
  KEY idx_dedicated_app_event_queue (organisation_id,status,risk_level,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (installation_id) REFERENCES dedicated_app_installations(id),
  FOREIGN KEY (actor_user_id) REFERENCES users(id),
  FOREIGN KEY (confirmed_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dedicated_app_sync_state (
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  installation_id BINARY(16) NOT NULL,
  server_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (organisation_id,project_id,installation_id),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (installation_id) REFERENCES dedicated_app_installations(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dedicated_app_sync_batches (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  installation_id BINARY(16) NOT NULL,
  actor_user_id BINARY(16) NOT NULL,
  client_batch_id VARCHAR(180) NOT NULL,
  base_version BIGINT UNSIGNED NOT NULL,
  server_version BIGINT UNSIGNED NOT NULL,
  status ENUM('applied','conflict','failed') NOT NULL,
  operations JSON NOT NULL,
  conflicts JSON NOT NULL,
  payload_sha256 CHAR(64) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_dedicated_app_batch (installation_id,client_batch_id),
  KEY idx_dedicated_app_sync_conflicts (organisation_id,status,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (installation_id) REFERENCES dedicated_app_installations(id),
  FOREIGN KEY (actor_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dedicated_app_notification_dispatches (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  workflow_event_id BINARY(16) NOT NULL,
  channel ENUM('in_app','email','push','sms','whatsapp') NOT NULL,
  status ENUM('queued','integration_required','sent','failed') NOT NULL,
  provider_reference VARCHAR(180) NULL,
  last_error_code VARCHAR(100) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  KEY idx_dedicated_app_dispatch (organisation_id,status,channel,created_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (workflow_event_id) REFERENCES dedicated_app_workflow_events(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
