CREATE TABLE IF NOT EXISTS municipal_project_profiles (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NOT NULL,
  application_type ENUM('building_plan','minor_works','consent_use','departure_relaxation','rezoning','subdivision','consolidation','removal_restrictive_title_condition','occupancy_certificate') NOT NULL,
  municipality VARCHAR(180) NOT NULL,
  profile_snapshot JSON NOT NULL,
  profile_sha256 CHAR(64) NOT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_by BINARY(16) NOT NULL,
  updated_by BINARY(16) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_municipal_profile_project (organisation_id,project_id),
  KEY idx_municipal_profiles (organisation_id,municipality,application_type,updated_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (updated_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

