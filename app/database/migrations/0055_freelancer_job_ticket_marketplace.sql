CREATE TABLE IF NOT EXISTS job_tickets (
  id BINARY(16) PRIMARY KEY,
  organisation_id BINARY(16) NOT NULL,
  project_id BINARY(16) NULL,
  parent_ticket_id BINARY(16) NULL,
  poster_user_id BINARY(16) NOT NULL,
  poster_type ENUM('client','registered_bep','contractor','subcontractor') NOT NULL,
  title VARCHAR(220) NOT NULL,
  description TEXT NOT NULL,
  deliverables JSON NOT NULL,
  budget_min DECIMAL(15,2) NOT NULL,
  budget_max DECIMAL(15,2) NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'ZAR',
  deadline DATE NOT NULL,
  location VARCHAR(220) NOT NULL,
  phase VARCHAR(80) NOT NULL,
  required_registrations JSON NOT NULL,
  invitation_type ENUM('public','direct') NOT NULL,
  platform_fee_percent DECIMAL(5,2) NOT NULL,
  platform_fee_disclosure VARCHAR(500) NOT NULL,
  classification_snapshot JSON NOT NULL,
  classification_sha256 CHAR(64) NOT NULL,
  automatic_award BOOLEAN NOT NULL DEFAULT FALSE,
  status ENUM('open','quoting','assigned','expanding','in_progress','completed','cancelled') NOT NULL DEFAULT 'open',
  holder_organisation_id BINARY(16) NULL,
  holder_user_id BINARY(16) NULL,
  accepted_quotation_id BINARY(16) NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  completed_at DATETIME(6) NULL,
  cancelled_at DATETIME(6) NULL,
  KEY idx_job_ticket_public_discovery (invitation_type,status,deadline,location,created_at),
  KEY idx_job_ticket_owner (organisation_id,poster_user_id,status,updated_at),
  KEY idx_job_ticket_project_tree (organisation_id,project_id,parent_ticket_id,status),
  KEY idx_job_ticket_holder (holder_organisation_id,holder_user_id,status,updated_at),
  FOREIGN KEY (organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (project_id) REFERENCES projects(id),
  FOREIGN KEY (parent_ticket_id) REFERENCES job_tickets(id),
  FOREIGN KEY (poster_user_id) REFERENCES users(id),
  FOREIGN KEY (holder_organisation_id) REFERENCES organisations(id),
  FOREIGN KEY (holder_user_id) REFERENCES users(id),
  CHECK (budget_min>=0 AND budget_max>=budget_min),
  CHECK (platform_fee_percent>=0 AND platform_fee_percent<=100),
  CHECK (automatic_award=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

