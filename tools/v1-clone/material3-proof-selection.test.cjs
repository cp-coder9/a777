'use strict';
const assert=require('node:assert/strict');
const {selectAcceptance,sourceExpectedInventory}=require('./material3-browser-menu-proof.cjs');
const inventory=sourceExpectedInventory();
const {ids,fullKeys:full}=inventory;
assert.equal(ids.length,49);
const tailIds=['drawing_compliance_navigator','valuations'];
assert.ok(tailIds.every(id=>ids.includes(id)));
assert.equal(full.length,517);
const profiles=selectAcceptance(full,ids,['--batch','profiles']);
assert.equal(profiles.expectedKeys.length,84);
const tail=selectAcceptance(full,ids,['--tools',tailIds.join(',')]);
assert.equal(tail.expectedKeys.length,16);
const rest=selectAcceptance(full,ids,['--batch','core','--tools',ids.filter(id=>!tailIds.includes(id)).join(',')]);
assert.equal(rest.expectedKeys.length,417);
const union=[...profiles.expectedKeys,...tail.expectedKeys,...rest.expectedKeys];
assert.equal(new Set(union).size,517);assert.equal(union.length,517);
assert.throws(()=>selectAcceptance(full,ids,['--tools','unknown']));
assert.throws(()=>selectAcceptance(full,ids,['--batch','profiles','--tools',ids[0]]));
assert.deepEqual(selectAcceptance(full,ids,[]).expectedKeys,full);
assert.deepEqual([...union].sort(),[...full].sort());
if(process.argv.includes('--inventory-json'))console.log(JSON.stringify(inventory));
else console.log('source-backed selection PASS: parent 517, profiles 84, Drawing Register/valuations 16, core 417, exact disjoint union');
